import { test,expect,type Page } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { readdir,readFile } from 'node:fs/promises';
import { Pool } from 'pg';
import { loadEnv } from 'vite';
import { totp } from '../fixtures/totp';
const env=loadEnv('test',process.cwd(),'');
const pool=new Pool({connectionString:env.DATABASE_URL});
const emails:string[]=[];
const password='A-secure-password-123!';
async function register(page:Page,name:string) {
  const email=`e2e-${randomUUID()}@example.test`;emails.push(email);
  await page.goto('/register');
  await page.getByLabel('Tên hiển thị').fill(name);await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Mật khẩu',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Tạo tài khoản',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('xác minh');
  const messages=await Promise.all((await readdir('.local/mail')).map(async f=>JSON.parse(await readFile(`.local/mail/${f}`,'utf8'))));
  const message=messages.find(m=>m.to===email && m.subject.includes('Xác minh'));
  await page.goto(message.text.match(/https?:\/\/\S+/)[0]);
  await page.goto('/login');await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Mật khẩu',{exact:true}).fill(password);await page.getByRole('button',{name:'Đăng nhập',exact:true}).click();
  await expect(page).toHaveURL(/\/settings$/);
  return email;
}
test.afterAll(async()=>{for(const email of emails) await pool.query('DELETE FROM "user" WHERE email=$1',[email]);await pool.end();});
test('registered seller submits application and an MFA admin reviews it',async({page,browser})=>{
  const ownerEmail=await register(page,'Nhà bán thử');
  await page.goto('/admin/users');await expect(page).toHaveURL(/access=denied/);
  await page.goto('/seller/onboarding');
  for(const [label,value] of [['Tên gian hàng','Shop thử E2E'],['Giới thiệu','Gian hàng kiểm tra đăng ký và duyệt.'],['Số điện thoại Việt Nam','0901234567'],['Họ tên cá nhân / tên pháp lý','Nguyễn Văn Thử'],['Địa chỉ gửi hàng','12 đường thử, Hà Nội'],['Ngân hàng','Ngân hàng thử'],['Số tài khoản','0123456789'],['Tên chủ tài khoản','NGUYEN VAN THU']]) await page.getByLabel(label,{exact:true}).fill(value);
  await page.getByRole('button',{name:'Gửi hồ sơ xét duyệt'}).click();
  await expect(page.getByText('Hồ sơ gian hàng đã được gửi')).toBeVisible();
  await page.goto('/seller');await expect(page.getByText('Đang xét duyệt',{exact:true})).toBeVisible();
  const context=await browser.newContext();const adminPage=await context.newPage();
  const adminEmail=await register(adminPage,'Quản trị thử');
  await adminPage.getByLabel('Mật khẩu hiện tại').fill(password);await adminPage.getByRole('button',{name:'Thiết lập xác thực hai bước'}).click();
  const secret=await adminPage.locator('code').textContent();expect(secret).toBeTruthy();
  await adminPage.getByLabel('Mã từ ứng dụng xác thực').fill(totp(secret!));await adminPage.getByRole('button',{name:'Xác nhận bật xác thực'}).click();
  await expect(adminPage.getByText('Đã bật xác thực hai bước.',{exact:true})).toBeVisible();
  await pool.query("INSERT INTO user_role(user_id,role) SELECT id,'admin' FROM \"user\" WHERE email=$1",[adminEmail]);
  await adminPage.goto('/admin/shops');
  const row=adminPage.getByRole('row').filter({hasText:'Shop thử E2E'});
  await row.getByLabel('Lý do xét duyệt').fill('Đã kiểm tra hồ sơ thử và thông tin nhận tiền');await row.getByRole('button',{name:'Lưu quyết định'}).click();
  await expect(row.getByText('Đã duyệt',{exact:true})).toBeVisible();
  await page.goto('/seller');await expect(page.getByText('Đã được duyệt',{exact:true})).toBeVisible();
  await page.goto('/settings');await page.getByRole('button',{name:'Đăng xuất',exact:true}).click();await expect(page).toHaveURL(/\/login$/);await page.goto('/seller');await expect(page).toHaveURL(/\/login$/);
  await context.close();
  expect(ownerEmail).not.toBe(adminEmail);
});
